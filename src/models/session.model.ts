import mongoose, { Schema, type HydratedDocument, type Types } from 'mongoose';
import { toJSON } from './plugins';

/**
 * One signed-in device.
 *
 * This is what makes signing out mean something. An access token is a signed
 * claim that cannot be taken back, so without a record on this side a phone
 * that logged out keeps working until its token happens to expire. Every
 * request checks that the session behind the token is still live.
 *
 * Not scoped to a practice, and deliberately not behind BaseRepository: a
 * person can belong to several clinics with one sign-in, so a practiceId
 * filter here would be meaningless at best and would hide a user's own session
 * from them at worst. The model is used directly.
 */
export type SessionRevokedReason = 'logout' | 'logout_all' | 'reuse_detected' | 'expired' | 'admin';

export interface ISession {
  userId: Types.ObjectId;
  /** Generated by the app on first install; stable across sign-ins on that phone. */
  deviceId: string;
  platform: 'ios' | 'android';
  appVersion: string;
  /** SHA-256 of the current refresh token. The token itself is never stored. */
  refreshTokenHash: string;
  /**
   * Stays the same while this session rotates its refresh token. An old token
   * from the same family coming back means one of the two holders is not the
   * phone, so the whole session goes.
   */
  refreshTokenFamily: string;
  lastUsedAt: Date;
  /** Slides forward on each refresh, capped at a fixed window from createdAt. */
  expiresAt: Date;
  revokedAt: Date | null;
  revokedReason: SessionRevokedReason | null;
  createdAt: Date;
  updatedAt: Date;
}

export type SessionDoc = HydratedDocument<ISession>;

const sessionSchema = new Schema<ISession>(
  {
    userId: { type: Schema.Types.ObjectId, ref: 'User', required: true },
    deviceId: { type: String, required: true },
    platform: { type: String, enum: ['ios', 'android'], required: true },
    appVersion: { type: String, default: '' },
    refreshTokenHash: { type: String, required: true, private: true },
    refreshTokenFamily: { type: String, required: true, private: true },
    lastUsedAt: { type: Date, default: () => new Date() },
    expiresAt: { type: Date, required: true },
    revokedAt: { type: Date, default: null },
    revokedReason: { type: String, default: null },
  },
  { timestamps: true },
);

sessionSchema.plugin(toJSON);

sessionSchema.index({ userId: 1, revokedAt: 1 });
sessionSchema.index({ refreshTokenHash: 1 }, { unique: true });
sessionSchema.index({ userId: 1, deviceId: 1 });
/**
 * Kept for a month after it expires, then Mongo clears it out. The month is so
 * that a question about who was signed in last week can still be answered;
 * after that the row is of no use to anybody.
 */
sessionSchema.index({ expiresAt: 1 }, { expireAfterSeconds: 2_592_000 });

export const Session = mongoose.model<ISession>('Session', sessionSchema, 'sessions');
export default Session;
