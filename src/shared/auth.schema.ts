import { z } from 'zod';
import { objectIdSchema, phoneSchema } from './common';
import { roleSchema } from './roles';

export const sendOtpBodySchema = z.object({
  phone: phoneSchema,
});
export type SendOtpBody = z.infer<typeof sendOtpBodySchema>;

/**
 * Which button was pressed.
 *
 * It decides one thing: whether a phone with no memberships gets a clinic of
 * its own. An assistant signing in before the doctor has added her must not,
 * or she ends up running her own clinic and then belonging to two. Defaulting
 * to signIn means the cautious answer is the one a caller gets by omission.
 */
export const authIntentSchema = z.enum(['signIn', 'signUp']);
export type AuthIntent = z.infer<typeof authIntentSchema>;

/**
 * The device signing in.
 *
 * `deviceId` is generated by the app on first install and stays the same
 * across sign-ins on that phone. It is what lets one phone hold one session:
 * verifying again on the same device retires the session that was there.
 */
export const deviceInfoSchema = z.object({
  deviceId: z.string().trim().min(8).max(128),
  platform: z.enum(['ios', 'android']),
  appVersion: z.string().trim().min(1).max(40),
});
export type DeviceInfo = z.infer<typeof deviceInfoSchema>;

export const verifyOtpBodySchema = z.object({
  phone: phoneSchema,
  code: z.string().regex(/^\d{6}$/, 'must be the 6 digit code'),
  /** Used when this sign-up creates a clinic, to name it and the person. */
  name: z.string().trim().min(1).max(120).optional(),
  intent: authIntentSchema.default('signIn'),
  ...deviceInfoSchema.shape,
});
export type VerifyOtpBody = z.infer<typeof verifyOtpBodySchema>;

/** Set up a clinic for a caller who signed in and has none. No body is required. */
export const createPracticeBodySchema = z.object({
  /** The doctor's name, when the app collected it on this screen. */
  name: z.string().trim().min(1).max(120).optional(),
});
export type CreatePracticeBody = z.infer<typeof createPracticeBodySchema>;

export const sendOtpResultSchema = z.object({
  sent: z.literal(true),
  /** Dev and test only: the code that was issued, so a sign-in needs no SMS. */
  devCode: z.string().optional(),
});
export type SendOtpResult = z.infer<typeof sendOtpResultSchema>;

export const refreshBodySchema = z.object({
  refreshToken: z.string().min(1),
});
export type RefreshBody = z.infer<typeof refreshBodySchema>;

/**
 * Signing out identifies the session from either credential.
 *
 * The refresh token is optional because an access token that is still valid
 * already says which session this is. It matters when the access token has
 * just expired: the app can still sign out cleanly rather than leaving a live
 * session behind on the server.
 */
export const logoutBodySchema = z.object({
  refreshToken: z.string().min(1).optional(),
});
export type LogoutBody = z.infer<typeof logoutBodySchema>;

export const logoutAllBodySchema = z.object({
  /** Leave the session making the request alone. */
  exceptCurrent: z.boolean().default(true),
});
export type LogoutAllBody = z.infer<typeof logoutAllBodySchema>;

export const tokenPairSchema = z.object({
  access: z.object({ token: z.string(), expires: z.coerce.date() }),
  refresh: z.object({ token: z.string(), expires: z.coerce.date() }),
});
export type TokenPair = z.infer<typeof tokenPairSchema>;

/** What a membership looks like to the app, with its locations resolved. */
export const membershipViewSchema = z.object({
  id: objectIdSchema,
  practiceId: objectIdSchema,
  practiceName: z.string(),
  role: roleSchema,
  locationIds: z.array(objectIdSchema),
  locations: z.array(
    z.object({
      id: objectIdSchema,
      name: z.string(),
      isDefault: z.boolean(),
      status: z.enum(['active', 'archived']),
    }),
  ),
});
export type MembershipView = z.infer<typeof membershipViewSchema>;

export const sessionSchema = z.object({
  user: z.object({
    id: objectIdSchema,
    phone: phoneSchema,
    name: z.string(),
    lastLoginAt: z.coerce.date().nullable(),
  }),
  memberships: z.array(membershipViewSchema),
  tokens: tokenPairSchema,
  /** Dev and test only: the code that was issued, so a sign-in needs no SMS. */
  devCode: z.string().optional(),
});
export type Session = z.infer<typeof sessionSchema>;
